-- 01_ddl.sql: creacion de la base de datos (DDL)
-- Plataforma de gamificacion del curso Pensamiento Computacional, Universidad Icesi.
-- Motor: Oracle Database 12c o superior, porque usa columnas IDENTITY.
-- Orden de ejecucion: 01_ddl, 02_dml, 03_dql, 04_plsql y 05_pruebas_plsql. Para reiniciar, ejecutar antes 00_drop_all.
-- Las tablas se crean en orden de dependencia: dominios, usuarios, cursos, actividades y puntajes.
-- Las llaves sustitutas son IDENTITY que inicia en 1000; los datos de prueba usan ids menores para que sean legibles.
-- La documentacion de cada tabla y columna queda tambien en el diccionario de datos con COMMENT ON.
-- MODULO DOMINIOS. Catalogos que reemplazan los atributos de texto libre (estado, tipo y dificultad).
-- USER_TYPE: rol del usuario. El trigger trg_app_user_valida_correo depende del nombre ESTUDIANTE.
CREATE TABLE user_type (
    id   NUMBER(2)    CONSTRAINT pk_user_type PRIMARY KEY,
    name VARCHAR2(20) NOT NULL CONSTRAINT uq_user_type_name UNIQUE
);
COMMENT ON TABLE user_type IS 'Dominio de roles de usuario: ESTUDIANTE, PROFESOR y ADMINISTRADOR.';
-- USER_STATUS: estado de la cuenta. Un usuario con historial no se borra, se pasa a INACTIVO.
CREATE TABLE user_status (
    id   NUMBER(2)    CONSTRAINT pk_user_status PRIMARY KEY,
    name VARCHAR2(20) NOT NULL CONSTRAINT uq_user_status_name UNIQUE
);
COMMENT ON TABLE user_status IS 'Dominio de estados de la cuenta: ACTIVO, INACTIVO y SUSPENDIDO.';
-- ACTIVITY_STATUS: ciclo de vida de una actividad (HU-08 y HU-16). Solo en ACTIVA se asignan puntos.
CREATE TABLE activity_status (
    id   NUMBER(2)    CONSTRAINT pk_activity_status PRIMARY KEY,
    name VARCHAR2(20) NOT NULL CONSTRAINT uq_activity_status_name UNIQUE
);
COMMENT ON TABLE activity_status IS 'Dominio de estados de una actividad: BORRADOR, ACTIVA y CERRADA.';
-- DIFFICULTY_SCALE: escala entera de 0 a 10 que exige la HU-09. El id es el valor de la escala.
CREATE TABLE difficulty_scale (
    id    NUMBER(2)    CONSTRAINT pk_difficulty_scale PRIMARY KEY,
    label VARCHAR2(30) NOT NULL CONSTRAINT uq_difficulty_scale_label UNIQUE,
    CONSTRAINT ck_difficulty_scale_rango CHECK (id BETWEEN 0 AND 10)
);
COMMENT ON TABLE difficulty_scale IS 'Dominio de dificultad de los ejercicios, de 0 a 10.';
COMMENT ON COLUMN difficulty_scale.id IS 'Valor de la dificultad, entero entre 0 y 10.';
COMMENT ON COLUMN difficulty_scale.label IS 'Nombre de la dificultad que se muestra al usuario.';
-- MODULO USUARIOS. APP_USER es el supertipo; ADMINISTRATOR, PROFESSOR y STUDENT son subtipos que comparten su llave.
-- LEVEL_RANK: categorias de desempeno y sus rangos de puntos, configurables (HU-15). max_points nulo significa sin tope.
CREATE TABLE level_rank (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_level_rank PRIMARY KEY,
    name       VARCHAR2(30) NOT NULL CONSTRAINT uq_level_rank_name UNIQUE,
    min_points NUMBER(6)    NOT NULL,
    max_points NUMBER(6),
    CONSTRAINT ck_level_rank_min CHECK (min_points >= 0),
    CONSTRAINT ck_level_rank_rango CHECK (max_points IS NULL OR max_points >= min_points)
);
COMMENT ON TABLE level_rank IS 'Categorias de desempeno del estudiante: Principiante, Killer y Pro.';
COMMENT ON COLUMN level_rank.min_points IS 'Puntos minimos del semestre para pertenecer a la categoria.';
COMMENT ON COLUMN level_rank.max_points IS 'Puntos maximos de la categoria. Nulo en la categoria mas alta.';
-- APP_USER: datos comunes de todo usuario (HU-01, HU-03, HU-04 y HU-17). Se llama APP_USER porque USER es palabra reservada.
-- Solo se guarda el hash de la contrasena: el CHECK de 60 caracteres impide guardar una contrasena en claro.
CREATE TABLE app_user (
    id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_app_user PRIMARY KEY,
    name                VARCHAR2(100) NOT NULL,
    institutional_email VARCHAR2(120) NOT NULL CONSTRAINT uq_app_user_email UNIQUE,
    photo_url           VARCHAR2(255),
    password_hash       VARCHAR2(255) NOT NULL,
    status_id           NUMBER(2)     NOT NULL CONSTRAINT fk_app_user_status REFERENCES user_status (id),
    user_type_id        NUMBER(2)     NOT NULL CONSTRAINT fk_app_user_type REFERENCES user_type (id),
    CONSTRAINT ck_app_user_email CHECK (institutional_email LIKE '%_@_%._%'),
    CONSTRAINT ck_app_user_hash CHECK (LENGTH(password_hash) >= 60)
);
COMMENT ON TABLE app_user IS 'Usuarios de la plataforma. Supertipo de administrador, profesor y estudiante.';
COMMENT ON COLUMN app_user.institutional_email IS 'Correo institucional, unico. Los estudiantes deben usar el dominio u.icesi.edu.co.';
COMMENT ON COLUMN app_user.photo_url IS 'Ruta de la foto de perfil. Opcional.';
COMMENT ON COLUMN app_user.password_hash IS 'Hash de la contrasena, de 60 caracteres o mas. Nunca la contrasena en claro.';
COMMENT ON COLUMN app_user.status_id IS 'Estado de la cuenta. Referencia a USER_STATUS.';
COMMENT ON COLUMN app_user.user_type_id IS 'Rol del usuario. Referencia a USER_TYPE.';
-- ADMINISTRATOR: usuarios que crean profesores y administran las cuentas (HU-04 y HU-17).
CREATE TABLE administrator (
    id NUMBER CONSTRAINT pk_administrator PRIMARY KEY
              CONSTRAINT fk_administrator_user REFERENCES app_user (id) ON DELETE CASCADE
);
COMMENT ON TABLE administrator IS 'Subtipo de APP_USER para los administradores.';
-- PROFESSOR: lo registra un administrador, no se autoregistra (HU-04).
CREATE TABLE professor (
    id            NUMBER CONSTRAINT pk_professor PRIMARY KEY
                         CONSTRAINT fk_professor_user REFERENCES app_user (id) ON DELETE CASCADE,
    employee_code VARCHAR2(20) NOT NULL CONSTRAINT uq_professor_code UNIQUE
);
COMMENT ON TABLE professor IS 'Subtipo de APP_USER para los profesores.';
COMMENT ON COLUMN professor.employee_code IS 'Codigo de empleado del profesor en la universidad, unico.';
-- STUDENT: guarda la categoria actual, que el trigger trg_score_actualiza_nivel mantiene al dia (HU-15).
CREATE TABLE student (
    id               NUMBER CONSTRAINT pk_student PRIMARY KEY
                            CONSTRAINT fk_student_user REFERENCES app_user (id) ON DELETE CASCADE,
    current_level_id NUMBER NOT NULL CONSTRAINT fk_student_level REFERENCES level_rank (id)
);
COMMENT ON TABLE student IS 'Subtipo de APP_USER para los estudiantes.';
COMMENT ON COLUMN student.current_level_id IS 'Categoria de desempeno segun los puntos del semestre activo. La recalcula un trigger.';
-- MODULO CURSOS. Semestres, grupos y matriculas.
-- SEMESTER: periodo academico (HU-07). active vale 1 en el semestre vigente y 0 en los demas.
CREATE TABLE semester (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_semester PRIMARY KEY,
    name       VARCHAR2(10) NOT NULL CONSTRAINT uq_semester_name UNIQUE,
    start_date DATE         NOT NULL,
    end_date   DATE         NOT NULL,
    active     NUMBER(1)    DEFAULT 0 NOT NULL,
    CONSTRAINT ck_semester_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_semester_fechas CHECK (end_date > start_date)
);
COMMENT ON TABLE semester IS 'Semestres academicos. Solo uno puede estar activo.';
COMMENT ON COLUMN semester.name IS 'Nombre del periodo, por ejemplo 2026-2.';
COMMENT ON COLUMN semester.active IS '1 si es el semestre vigente, 0 en caso contrario.';
-- Indice unico funcional: la expresion solo tiene valor en la fila activa, asi que no puede haber dos semestres activos.
CREATE UNIQUE INDEX uq_semester_activo ON semester (CASE WHEN active = 1 THEN 1 END);
-- COURSE_GROUP: grupo del curso en un semestre, a cargo de un profesor (HU-02 y HU-06).
-- El nombre se puede repetir en semestres distintos (G3 en 2026-1 y en 2026-2), pero no dentro del mismo.
CREATE TABLE course_group (
    id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_course_group PRIMARY KEY,
    name         VARCHAR2(10) NOT NULL,
    semester_id  NUMBER       NOT NULL CONSTRAINT fk_course_group_semester REFERENCES semester (id),
    professor_id NUMBER       NOT NULL CONSTRAINT fk_course_group_professor REFERENCES professor (id),
    CONSTRAINT uq_course_group_nombre UNIQUE (name, semester_id)
);
COMMENT ON TABLE course_group IS 'Grupos del curso por semestre. Se llama COURSE_GROUP porque GROUP es palabra reservada.';
COMMENT ON COLUMN course_group.name IS 'Nombre del grupo, por ejemplo G1. Unico dentro del semestre.';
COMMENT ON COLUMN course_group.professor_id IS 'Profesor que dicta el grupo.';
-- ENROLLMENT: registro de un estudiante en un grupo (HU-02). Un estudiante no se matricula dos veces en el mismo grupo.
CREATE TABLE enrollment (
    id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_enrollment PRIMARY KEY,
    student_id        NUMBER    NOT NULL CONSTRAINT fk_enrollment_student REFERENCES student (id),
    group_id          NUMBER    NOT NULL CONSTRAINT fk_enrollment_group REFERENCES course_group (id),
    registration_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_enrollment UNIQUE (student_id, group_id)
);
COMMENT ON TABLE enrollment IS 'Matricula de los estudiantes en los grupos.';
COMMENT ON COLUMN enrollment.registration_date IS 'Fecha y hora en que el estudiante se registro en el grupo.';
-- MODULO ACTIVIDADES Y PUNTAJES.
-- EXERCISE: ejercicio de programacion con consigna, dificultad y categoria a la que se dirige (HU-09).
CREATE TABLE exercise (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_exercise PRIMARY KEY,
    statement     CLOB      NOT NULL,
    difficulty_id NUMBER(2) NOT NULL CONSTRAINT fk_exercise_difficulty REFERENCES difficulty_scale (id),
    level_id      NUMBER    NOT NULL CONSTRAINT fk_exercise_level REFERENCES level_rank (id)
);
COMMENT ON TABLE exercise IS 'Banco de ejercicios de programacion.';
COMMENT ON COLUMN exercise.statement IS 'Consigna del ejercicio. CLOB para admitir texto extenso.';
COMMENT ON COLUMN exercise.difficulty_id IS 'Dificultad de 0 a 10. Referencia a DIFFICULTY_SCALE.';
COMMENT ON COLUMN exercise.level_id IS 'Categoria de estudiante a la que se dirige el ejercicio.';
-- ACTIVITY: conjunto de ejercicios que un profesor aplica a un grupo en una ventana de tiempo (HU-08 y HU-16).
CREATE TABLE activity (
    id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_activity PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL,
    start_date   TIMESTAMP     NOT NULL,
    end_date     TIMESTAMP     NOT NULL,
    status_id    NUMBER(2)     NOT NULL CONSTRAINT fk_activity_status REFERENCES activity_status (id),
    professor_id NUMBER        NOT NULL CONSTRAINT fk_activity_professor REFERENCES professor (id),
    group_id     NUMBER        NOT NULL CONSTRAINT fk_activity_group REFERENCES course_group (id),
    CONSTRAINT ck_activity_fechas CHECK (end_date > start_date)
);
COMMENT ON TABLE activity IS 'Actividades de clase, compuestas por uno o varios ejercicios.';
COMMENT ON COLUMN activity.start_date IS 'Inicio de la ventana en que los estudiantes pueden resolver la actividad.';
COMMENT ON COLUMN activity.end_date IS 'Fin de la ventana de la actividad.';
COMMENT ON COLUMN activity.professor_id IS 'Profesor que crea la actividad y el unico que puede asignar sus puntos.';
-- ACTIVITY_EXERCISE: resuelve la relacion muchos a muchos entre actividad y ejercicio, con el orden de presentacion.
CREATE TABLE activity_exercise (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_activity_exercise PRIMARY KEY,
    activity_id NUMBER    NOT NULL CONSTRAINT fk_activity_exercise_activity REFERENCES activity (id),
    exercise_id NUMBER    NOT NULL CONSTRAINT fk_activity_exercise_exercise REFERENCES exercise (id),
    order_num   NUMBER(3) NOT NULL,
    CONSTRAINT uq_activity_exercise UNIQUE (activity_id, exercise_id),
    CONSTRAINT uq_activity_exercise_orden UNIQUE (activity_id, order_num),
    CONSTRAINT ck_activity_exercise_orden CHECK (order_num > 0)
);
COMMENT ON TABLE activity_exercise IS 'Ejercicios que componen cada actividad.';
COMMENT ON COLUMN activity_exercise.order_num IS 'Posicion del ejercicio dentro de la actividad, desde 1.';
-- SCORE: puntos que un profesor asigna a un estudiante por un ejercicio de una actividad (HU-10).
-- uq_score_estudiante_ejercicio evita la doble asignacion y uq_score_codigo impide reutilizar un codigo o QR.
CREATE TABLE score (
    id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) CONSTRAINT pk_score PRIMARY KEY,
    points               NUMBER(4)    NOT NULL,
    award_date           TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    student_id           NUMBER       NOT NULL CONSTRAINT fk_score_student REFERENCES student (id),
    activity_exercise_id NUMBER       NOT NULL CONSTRAINT fk_score_activity_exercise REFERENCES activity_exercise (id),
    professor_id         NUMBER       NOT NULL CONSTRAINT fk_score_professor REFERENCES professor (id),
    group_id             NUMBER       NOT NULL CONSTRAINT fk_score_group REFERENCES course_group (id),
    redemption_code      VARCHAR2(30) CONSTRAINT uq_score_codigo UNIQUE,
    CONSTRAINT uq_score_estudiante_ejercicio UNIQUE (student_id, activity_exercise_id),
    CONSTRAINT ck_score_points CHECK (points > 0)
);
COMMENT ON TABLE score IS 'Puntajes asignados por los profesores. Base del podium, los historiales y las categorias.';
COMMENT ON COLUMN score.points IS 'Puntos otorgados, entero mayor que cero.';
COMMENT ON COLUMN score.award_date IS 'Fecha y hora de la asignacion.';
COMMENT ON COLUMN score.group_id IS 'Grupo en el que el estudiante obtuvo los puntos. Permite filtrar por semestre sin pasar por la actividad.';
COMMENT ON COLUMN score.redemption_code IS 'Codigo alfanumerico o de QR con el que se redimieron los puntos. Opcional y unico.';
-- INDICES sobre llaves foraneas que no encabezan una llave primaria o unica.
-- Aceleran los joins de los reportes y evitan bloqueos de tabla al modificar las tablas padre.
CREATE INDEX ix_app_user_status ON app_user (status_id);
CREATE INDEX ix_app_user_type ON app_user (user_type_id);
CREATE INDEX ix_student_level ON student (current_level_id);
CREATE INDEX ix_course_group_semester ON course_group (semester_id);
CREATE INDEX ix_course_group_professor ON course_group (professor_id);
CREATE INDEX ix_enrollment_group ON enrollment (group_id);
CREATE INDEX ix_exercise_difficulty ON exercise (difficulty_id);
CREATE INDEX ix_exercise_level ON exercise (level_id);
CREATE INDEX ix_activity_status ON activity (status_id);
CREATE INDEX ix_activity_professor ON activity (professor_id);
CREATE INDEX ix_activity_group ON activity (group_id);
CREATE INDEX ix_activity_exercise_exercise ON activity_exercise (exercise_id);
CREATE INDEX ix_score_activity_exercise ON score (activity_exercise_id);
CREATE INDEX ix_score_professor ON score (professor_id);
CREATE INDEX ix_score_group ON score (group_id);
