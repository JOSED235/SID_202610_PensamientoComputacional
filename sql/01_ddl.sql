-- ---------------------------------------------------------------------
-- 1. TABLAS DE DOMINIO Y CATALOGOS
-- ---------------------------------------------------------------------

CREATE TABLE user_type (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    name VARCHAR2(50) NOT NULL CONSTRAINT uq_user_type_name UNIQUE
);
COMMENT ON TABLE user_type IS 'Catalogo de tipos de usuario del sistema (ESTUDIANTE, PROFESOR, ADMINISTRADOR)';
COMMENT ON COLUMN user_type.id IS 'Identificador unico del tipo de usuario';
COMMENT ON COLUMN user_type.name IS 'Nombre descriptivo del tipo de usuario';

CREATE TABLE user_status (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    name VARCHAR2(50) NOT NULL CONSTRAINT uq_user_status_name UNIQUE
);
COMMENT ON TABLE user_status IS 'Catalogo de estados de la cuenta de usuario (ACTIVO, INACTIVO, SUSPENDIDO)';
COMMENT ON COLUMN user_status.id IS 'Identificador unico del estado de usuario';
COMMENT ON COLUMN user_status.name IS 'Nombre del estado';

CREATE TABLE activity_status (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    name VARCHAR2(50) NOT NULL CONSTRAINT uq_activity_status_name UNIQUE
);
COMMENT ON TABLE activity_status IS 'Catalogo de estados de una actividad evaluativa (BORRADOR, ACTIVA, CERRADA)';
COMMENT ON COLUMN activity_status.id IS 'Identificador unico del estado de actividad';
COMMENT ON COLUMN activity_status.name IS 'Nombre del estado';

CREATE TABLE difficulty_scale (
    id    NUMBER PRIMARY KEY CONSTRAINT chk_diff_id_range CHECK (id BETWEEN 0 AND 10),
    label VARCHAR2(50) NOT NULL
);
COMMENT ON TABLE difficulty_scale IS 'Escala discreta de dificultad para ejercicios (valores de 0 a 10)';
COMMENT ON COLUMN difficulty_scale.id IS 'Valor numerico de dificultad entre 0 y 10';
COMMENT ON COLUMN difficulty_scale.label IS 'Etiqueta textual descriptiva de la dificultad';

CREATE TABLE level_rank (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    name       VARCHAR2(50) NOT NULL CONSTRAINT uq_level_rank_name UNIQUE,
    min_points NUMBER NOT NULL CONSTRAINT chk_level_min_pts CHECK (min_points >= 0),
    max_points NUMBER CONSTRAINT chk_level_max_pts CHECK (max_points IS NULL OR max_points >= min_points)
);
COMMENT ON TABLE level_rank IS 'Categorias de desempeno de estudiantes segun puntos acumulados (Principiante, Killer, Pro)';
COMMENT ON COLUMN level_rank.id IS 'Identificador unico de la categoria';
COMMENT ON COLUMN level_rank.name IS 'Nombre de la categoria (Principiante, Killer, Pro)';
COMMENT ON COLUMN level_rank.min_points IS 'Puntaje minimo necesario para clasificar en el rango';
COMMENT ON COLUMN level_rank.max_points IS 'Puntaje maximo del rango (NULL para la categoria superior sin limite)';

-- ---------------------------------------------------------------------
-- 2. MODULO DE USUARIOS Y ROLES (Jerarquia de herencia sobre APP_USER)
-- ---------------------------------------------------------------------

CREATE TABLE app_user (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name                VARCHAR2(150) NOT NULL,
    institutional_email VARCHAR2(150) NOT NULL CONSTRAINT uq_app_user_email UNIQUE,
    photo_url           VARCHAR2(500),
    password_hash       VARCHAR2(255) NOT NULL,
    status_id           NUMBER NOT NULL,
    user_type_id        NUMBER NOT NULL,
    CONSTRAINT fk_app_user_status FOREIGN KEY (status_id) REFERENCES user_status(id),
    CONSTRAINT fk_app_user_type FOREIGN KEY (user_type_id) REFERENCES user_type(id),
    CONSTRAINT chk_app_user_pw_hash CHECK (LENGTH(password_hash) >= 60)
);
COMMENT ON TABLE app_user IS 'Entidad base de usuarios del sistema';
COMMENT ON COLUMN app_user.id IS 'Identificador unico del usuario';
COMMENT ON COLUMN app_user.name IS 'Nombre completo del usuario';
COMMENT ON COLUMN app_user.institutional_email IS 'Correo electronico institucional unico';
COMMENT ON COLUMN app_user.photo_url IS 'Ruta o URL opcional de la foto de perfil';
COMMENT ON COLUMN app_user.password_hash IS 'Hash seguro de la contrasena (longitud minima 60 chars ej. bcrypt)';
COMMENT ON COLUMN app_user.status_id IS 'FK al catalogo de estado de cuenta';
COMMENT ON COLUMN app_user.user_type_id IS 'FK al catalogo de tipo de usuario';

CREATE TABLE administrator (
    id NUMBER PRIMARY KEY,
    CONSTRAINT fk_admin_user FOREIGN KEY (id) REFERENCES app_user(id) ON DELETE CASCADE
);
COMMENT ON TABLE administrator IS 'Subtipo de usuario con rol Administrador de la plataforma';
COMMENT ON COLUMN administrator.id IS 'PK y FK que referencia a APP_USER(id)';

CREATE TABLE professor (
    id            NUMBER PRIMARY KEY,
    employee_code VARCHAR2(50) NOT NULL CONSTRAINT uq_prof_code UNIQUE,
    CONSTRAINT fk_prof_user FOREIGN KEY (id) REFERENCES app_user(id) ON DELETE CASCADE
);
COMMENT ON TABLE professor IS 'Subtipo de usuario con rol Profesor del curso';
COMMENT ON COLUMN professor.id IS 'PK y FK que referencia a APP_USER(id)';
COMMENT ON COLUMN professor.employee_code IS 'Codigo de empleado o docente unico';

CREATE TABLE student (
    id               NUMBER PRIMARY KEY,
    current_level_id NUMBER NOT NULL,
    CONSTRAINT fk_student_user FOREIGN KEY (id) REFERENCES app_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_student_level FOREIGN KEY (current_level_id) REFERENCES level_rank(id)
);
COMMENT ON TABLE student IS 'Subtipo de usuario con rol Estudiante';
COMMENT ON COLUMN student.id IS 'PK y FK que referencia a APP_USER(id)';
COMMENT ON COLUMN student.current_level_id IS 'FK a LEVEL_RANK que indica la categoria actual alcanzada';

-- ---------------------------------------------------------------------
-- 3. MODULO ACADEMICO (Semestres, Grupos y Matriculas)
-- ---------------------------------------------------------------------

CREATE TABLE semester (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name       VARCHAR2(50) NOT NULL CONSTRAINT uq_semester_name UNIQUE,
    start_date DATE NOT NULL,
    end_date   DATE NOT NULL,
    active     NUMBER(1) DEFAULT 0 NOT NULL CONSTRAINT chk_semester_active CHECK (active IN (0, 1)),
    CONSTRAINT chk_semester_dates CHECK (end_date >= start_date)
);
COMMENT ON TABLE semester IS 'Periodos academicos del curso';
COMMENT ON COLUMN semester.id IS 'Identificador unico del semestre';
COMMENT ON COLUMN semester.name IS 'Nombre del periodo academico (ej. 2026-2)';
COMMENT ON COLUMN semester.start_date IS 'Fecha de inicio del semestre';
COMMENT ON COLUMN semester.end_date IS 'Fecha de finalizacion del semestre';
COMMENT ON COLUMN semester.active IS 'Indicador booleano: 1 si es el semestre activo vigente, 0 en otro caso';

-- Indice unico funcional: garantiza que a nivel de motor exista unicamente un semestre activo
CREATE UNIQUE INDEX uq_semester_active_only_one ON semester (
    CASE WHEN active = 1 THEN 1 ELSE NULL END
);

CREATE TABLE course_group (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name         VARCHAR2(50) NOT NULL,
    semester_id  NUMBER NOT NULL,
    professor_id NUMBER NOT NULL,
    CONSTRAINT fk_group_semester FOREIGN KEY (semester_id) REFERENCES semester(id),
    CONSTRAINT fk_group_professor FOREIGN KEY (professor_id) REFERENCES professor(id),
    CONSTRAINT uq_group_name_per_semester UNIQUE (name, semester_id)
);
COMMENT ON TABLE course_group IS 'Grupos de clase del curso ofertados por semestre';
COMMENT ON COLUMN course_group.id IS 'Identificador unico del grupo';
COMMENT ON COLUMN course_group.name IS 'Nombre o codigo del grupo (ej. G1, G3)';
COMMENT ON COLUMN course_group.semester_id IS 'FK al semestre en el cual se oferta el grupo';
COMMENT ON COLUMN course_group.professor_id IS 'FK al profesor titular responsable del grupo';

CREATE TABLE enrollment (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    student_id        NUMBER NOT NULL,
    group_id          NUMBER NOT NULL,
    registration_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_enroll_student FOREIGN KEY (student_id) REFERENCES student(id),
    CONSTRAINT fk_enroll_group FOREIGN KEY (group_id) REFERENCES course_group(id),
    CONSTRAINT uq_enroll_student_group UNIQUE (student_id, group_id)
);
COMMENT ON TABLE enrollment IS 'Registro de matricula de un estudiante en un grupo de clase';
COMMENT ON COLUMN enrollment.id IS 'Identificador unico de la matricula';
COMMENT ON COLUMN enrollment.student_id IS 'FK al estudiante matriculado';
COMMENT ON COLUMN enrollment.group_id IS 'FK al grupo en el que se matricula';
COMMENT ON COLUMN enrollment.registration_date IS 'Fecha y hora en que se registro la matricula';

-- ---------------------------------------------------------------------
-- 4. MODULO DE ACTIVIDADES, EJERCICIOS Y PUNTAJES (3FN)
-- ---------------------------------------------------------------------

CREATE TABLE exercise (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    statement     CLOB NOT NULL,
    difficulty_id NUMBER NOT NULL,
    level_id      NUMBER NOT NULL,
    CONSTRAINT fk_exercise_diff FOREIGN KEY (difficulty_id) REFERENCES difficulty_scale(id),
    CONSTRAINT fk_exercise_level FOREIGN KEY (level_id) REFERENCES level_rank(id)
);
COMMENT ON TABLE exercise IS 'Banco de ejercicios de programacion';
COMMENT ON COLUMN exercise.id IS 'Identificador unico del ejercicio';
COMMENT ON COLUMN exercise.statement IS 'Enunciado detallado de la consigna del ejercicio';
COMMENT ON COLUMN exercise.difficulty_id IS 'FK a la escala de dificultad (0 a 10)';
COMMENT ON COLUMN exercise.level_id IS 'FK al perfil/categoria objetivo (Principiante, Killer, Pro)';

CREATE TABLE activity (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name         VARCHAR2(150) NOT NULL,
    start_date   TIMESTAMP NOT NULL,
    end_date     TIMESTAMP NOT NULL,
    status_id    NUMBER NOT NULL,
    professor_id NUMBER NOT NULL,
    group_id     NUMBER NOT NULL,
    CONSTRAINT fk_activity_status FOREIGN KEY (status_id) REFERENCES activity_status(id),
    CONSTRAINT fk_activity_professor FOREIGN KEY (professor_id) REFERENCES professor(id),
    CONSTRAINT fk_activity_group FOREIGN KEY (group_id) REFERENCES course_group(id),
    CONSTRAINT chk_activity_dates CHECK (end_date >= start_date)
);
COMMENT ON TABLE activity IS 'Actividades evaluativas compuestas por ejercicios, programadas para un grupo';
COMMENT ON COLUMN activity.id IS 'Identificador unico de la actividad';
COMMENT ON COLUMN activity.name IS 'Nombre de la actividad (ej. Ciclos, Condicionales)';
COMMENT ON COLUMN activity.start_date IS 'Fecha y hora de inicio / apertura de la actividad';
COMMENT ON COLUMN activity.end_date IS 'Fecha y hora de cierre de la actividad';
COMMENT ON COLUMN activity.status_id IS 'FK al estado de la actividad (BORRADOR, ACTIVA, CERRADA)';
COMMENT ON COLUMN activity.professor_id IS 'FK al profesor que creo y gestiona la actividad';
COMMENT ON COLUMN activity.group_id IS 'FK al grupo de clase destinatario';

CREATE TABLE activity_exercise (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    activity_id NUMBER NOT NULL,
    exercise_id NUMBER NOT NULL,
    order_num   NUMBER NOT NULL CONSTRAINT chk_ae_order_pos CHECK (order_num > 0),
    CONSTRAINT fk_ae_activity FOREIGN KEY (activity_id) REFERENCES activity(id) ON DELETE CASCADE,
    CONSTRAINT fk_ae_exercise FOREIGN KEY (exercise_id) REFERENCES exercise(id),
    CONSTRAINT uq_ae_activity_exercise UNIQUE (activity_id, exercise_id)
);
COMMENT ON TABLE activity_exercise IS 'Asociacion de ejercicios a una actividad especifica con su orden de aparicion';
COMMENT ON COLUMN activity_exercise.id IS 'Identificador unico del ejercicio dentro de la actividad';
COMMENT ON COLUMN activity_exercise.activity_id IS 'FK a la actividad';
COMMENT ON COLUMN activity_exercise.exercise_id IS 'FK al ejercicio asignado';
COMMENT ON COLUMN activity_exercise.order_num IS 'Orden relativo de presentacion del ejercicio en la actividad';

-- Tabla SCORE en estricta Tercera Forma Normal (3FN):
-- Se incluye group_id como atributo por compatibilidad transaccional y optimizacion de consultas,
-- o derivable mediante activity_exercise -> activity -> group_id segun la regla documentada.
CREATE TABLE score (
    id                   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    points               NUMBER NOT NULL CONSTRAINT chk_score_points_pos CHECK (points > 0),
    award_date           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    student_id           NUMBER NOT NULL,
    activity_exercise_id NUMBER NOT NULL,
    professor_id         NUMBER NOT NULL,
    redemption_code      VARCHAR2(100) CONSTRAINT uq_score_redemption_code UNIQUE,
    CONSTRAINT fk_score_student FOREIGN KEY (student_id) REFERENCES student(id),
    CONSTRAINT fk_score_act_ex FOREIGN KEY (activity_exercise_id) REFERENCES activity_exercise(id),
    CONSTRAINT fk_score_professor FOREIGN KEY (professor_id) REFERENCES professor(id),
    CONSTRAINT uq_score_student_exercise UNIQUE (student_id, activity_exercise_id)
);
COMMENT ON TABLE score IS 'Registro de puntos otorgados a un estudiante por la resolucion de un ejercicio';
COMMENT ON COLUMN score.id IS 'Identificador unico del puntaje';
COMMENT ON COLUMN score.points IS 'Cantidad de puntos asignados (> 0)';
COMMENT ON COLUMN score.award_date IS 'Fecha y hora exacta en la que se otorgo la puntuacion';
COMMENT ON COLUMN score.student_id IS 'FK al estudiante calificado';
COMMENT ON COLUMN score.activity_exercise_id IS 'FK al ejercicio de la actividad evaluado';
COMMENT ON COLUMN score.professor_id IS 'FK al profesor que califico y asigno los puntos';
COMMENT ON COLUMN score.redemption_code IS 'Codigo alfanumerico o QR unico usado para redimir los puntos';

-- ---------------------------------------------------------------------
-- 5. INDICES ADICIONALES PARA MEJORA DE RENDIMIENTO EN LLAVES FORANEAS
-- ---------------------------------------------------------------------
CREATE INDEX idx_enrollment_student ON enrollment(student_id);
CREATE INDEX idx_enrollment_group ON enrollment(group_id);
CREATE INDEX idx_course_group_prof ON course_group(professor_id);
CREATE INDEX idx_course_group_sem ON course_group(semester_id);
CREATE INDEX idx_activity_group ON activity(group_id);
CREATE INDEX idx_activity_prof ON activity(professor_id);
CREATE INDEX idx_activity_exercise_act ON activity_exercise(activity_id);
CREATE INDEX idx_activity_exercise_ex ON activity_exercise(exercise_id);
CREATE INDEX idx_score_student ON score(student_id);
CREATE INDEX idx_score_act_ex ON score(activity_exercise_id);
